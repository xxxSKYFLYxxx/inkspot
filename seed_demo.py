ICON_BY_CATEGORY = {
    'tech':      '⌬',
    'design':    '✦',
    'education': '✎',
    'travel':    '✈',
    'lifestyle': '❀',
}


def create_cover(category_slug, title, out_path, size=(1200, 700)):
    palettes = COVER_THEMES.get(category_slug, COVER_THEMES['lifestyle'])
    a, b = random.choice(palettes)
    img = make_gradient(size, hex_to_rgb(a), hex_to_rgb(b))

    # полупрозрачные круги для глубины
    overlay = Image.new('RGBA', size, (0, 0, 0, 0))
    od = ImageDraw.Draw(overlay)
    for _ in range(7):
        r = random.randint(80, 260)
        x = random.randint(-50, size[0])
        y = random.randint(-50, size[1])
        alpha = random.randint(18, 50)
        od.ellipse((x - r, y - r, x + r, y + r),
                   fill=(255, 255, 255, alpha))
    overlay = overlay.filter(ImageFilter.GaussianBlur(radius=18))
    img = Image.alpha_composite(img.convert('RGBA'), overlay)

    # затемнение снизу для читаемости
    grad_dim = Image.new('RGBA', size, (0, 0, 0, 0))
    gd = grad_dim.load()
    for y in range(size[1]):
        a_val = int(140 * (y / size[1]) ** 2)
        for x in range(size[0]):
            gd[x, y] = (0, 0, 0, a_val)
    img = Image.alpha_composite(img, grad_dim)

    draw = ImageDraw.Draw(img)

    # иконка категории сверху-слева
    icon = ICON_BY_CATEGORY.get(category_slug, '✶')
    icon_font = find_font(120)
    draw.text((60, 50), icon, fill=(255, 255, 255, 200), font=icon_font)

    # заголовок (с переносами)
    title_font = find_font(60, bold=True)
    max_w = size[0] - 120
    words = title.split()
    lines, cur = [], ''
    for w in words:
        test = (cur + ' ' + w).strip()
        if draw.textlength(test, font=title_font) <= max_w:
            cur = test
        else:
            if cur:
                lines.append(cur)
            cur = w
    if cur:
        lines.append(cur)

    line_h = 72
    total_h = line_h * len(lines)
    y = size[1] - total_h - 80
    for line in lines:
        draw.text((60, y), line, fill=(255, 255, 255, 250), font=title_font)
        y += line_h

    img.convert('RGB').save(out_path, 'JPEG', quality=88)


