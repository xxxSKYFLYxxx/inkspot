def hex_to_rgb(h):
    h = h.lstrip('#')
    return tuple(int(h[i:i+2], 16) for i in (0, 2, 4))


def make_gradient(size, color_a, color_b, diagonal=True):
    w, h = size
    base = Image.new('RGB', size, color_a)
    top = Image.new('RGB', size, color_b)
    mask = Image.new('L', size)
    md = mask.load()
    for y in range(h):
        for x in range(w):
            if diagonal:
                md[x, y] = int(255 * ((x + y) / (w + h)))
            else:
                md[x, y] = int(255 * (y / h))
    base.paste(top, (0, 0), mask)
    return base


def create_avatar(initials, palette, out_path, size=256):
    a, b = palette
    grad = make_gradient((size, size), hex_to_rgb(a), hex_to_rgb(b))

    # обрезаем в круг
    avatar = Image.new('RGBA', (size, size), (0, 0, 0, 0))
    mask = Image.new('L', (size, size), 0)
    ImageDraw.Draw(mask).ellipse((0, 0, size, size), fill=255)
    avatar.paste(grad, (0, 0), mask)

    # инициалы
    draw = ImageDraw.Draw(avatar)
    font = find_font(int(size * 0.42), bold=True)
    bbox = draw.textbbox((0, 0), initials, font=font)
    tw, th = bbox[2] - bbox[0], bbox[3] - bbox[1]
    draw.text(
        ((size - tw) / 2 - bbox[0], (size - th) / 2 - bbox[1] - 4),
        initials, fill=(255, 255, 255, 240), font=font
    )

    avatar.save(out_path, 'PNG')


