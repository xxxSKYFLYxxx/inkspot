        print('Создание пользователей и аватарок…')
        created_users = {}
        for i, u in enumerate(USERS):
            existing = User.query.filter_by(username=u['username']).first()
            if existing:
                created_users[u['username']] = existing
                continue
            user = User(
                username=u['username'],
                email=u['email'],
                bio=u['bio'],
                created_at=datetime.utcnow() - timedelta(days=random.randint(60, 400)),
            )
            user.set_password('demo1234')
            avatar_name = f"avatar_{u['username']}.png"
            create_avatar(
                u['initials'],
                AVATAR_PALETTES[i % len(AVATAR_PALETTES)],
                os.path.join(UPLOAD_DIR, avatar_name),
            )
            user.avatar = avatar_name
            db.session.add(user)
            created_users[u['username']] = user
        db.session.commit()

        # обновим аватарку у admin, если её нет
        admin = User.query.filter_by(username='admin').first()
