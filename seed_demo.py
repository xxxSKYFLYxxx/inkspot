# ─── Сборка ──────────────────────────────────────────────────────────────────
def slug_to_category(slug):
    return Category.query.filter_by(slug=slug).first()


def wipe():
    print('Очистка существующих данных…')
    Comment.query.delete()
    db.session.execute(db.text('DELETE FROM post_likes'))
    Post.query.delete()
    # сохраняем admin и системные категории
    User.query.filter(User.is_admin == False).delete()  # noqa: E712
    db.session.commit()


